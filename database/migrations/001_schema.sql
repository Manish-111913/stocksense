-- 17. stock_ledger (append-only; one row per affected location)
CREATE TABLE stock_ledger (
  id                       UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  product_id               UUID NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
  warehouse_id             UUID NOT NULL REFERENCES warehouses (id) ON DELETE RESTRICT,
  location_id              UUID NOT NULL,
  movement_type            inventory_operation NOT NULL,
  direction                ledger_direction NOT NULL,
  quantity                 NUMERIC(18,3) NOT NULL CHECK (quantity > 0), -- magnitude; direction gives the sign
  source_location_id       UUID REFERENCES locations (id) ON DELETE RESTRICT,
  destination_location_id  UUID REFERENCES locations (id) ON DELETE RESTRICT,
  reference_type           inventory_operation NOT NULL,
  reference_id             UUID NOT NULL,        -- id of the receipt / delivery / transfer / adjustment
  reference_code           VARCHAR(50) NOT NULL, -- its human-readable reference (WH/IN/000001) for display
  quantity_before          NUMERIC(18,3) CHECK (quantity_before >= 0),
  quantity_after           NUMERIC(18,3) CHECK (quantity_after >= 0),
  performed_by             UUID NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT stock_ledger_location_in_warehouse_fk
    FOREIGN KEY (location_id, warehouse_id) REFERENCES locations (id, warehouse_id) ON DELETE RESTRICT,
  CONSTRAINT stock_ledger_balance_matches CHECK (
    quantity_before IS NULL OR quantity_after IS NULL OR
    quantity_after = quantity_before + CASE WHEN direction IN ('OUT', 'ADJUSTMENT_OUT') THEN -quantity ELSE quantity END
  )
);
CREATE INDEX stock_ledger_product_id_idx ON stock_ledger (product_id);
CREATE INDEX stock_ledger_location_id_idx ON stock_ledger (location_id);
CREATE INDEX stock_ledger_movement_type_idx ON stock_ledger (movement_type);
CREATE INDEX stock_ledger_created_at_idx ON stock_ledger (created_at DESC);
CREATE INDEX stock_ledger_reference_id_idx ON stock_ledger (reference_id);

-- The ledger is history: the application may only INSERT
CREATE FUNCTION stock_ledger_is_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'stock_ledger is append-only: % is not allowed', TG_OP;
END;
$$;

CREATE TRIGGER stock_ledger_no_update_delete
  BEFORE UPDATE OR DELETE ON stock_ledger
  FOR EACH ROW EXECUTE FUNCTION stock_ledger_is_append_only();

CREATE TRIGGER stock_ledger_no_truncate
  BEFORE TRUNCATE ON stock_ledger
  FOR EACH STATEMENT EXECUTE FUNCTION stock_ledger_is_append_only();

-- ---------------------------------------------------------------------
-- updated_at triggers
-- ---------------------------------------------------------------------
DO $$
DECLARE
  t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'users', 'categories', 'products', 'warehouses', 'locations', 'suppliers', 'customers', 'stock',
    'receipts', 'receipt_items', 'deliveries', 'delivery_items',
    'internal_transfers', 'internal_transfer_items', 'inventory_adjustments'
  ] LOOP
    EXECUTE format('CREATE TRIGGER %I_set_updated_at BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()', t, t);
  END LOOP;
END;
$$;
