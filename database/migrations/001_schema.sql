-- 14. internal_transfers
CREATE TABLE internal_transfers (
  id                        UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  reference                 VARCHAR(50) NOT NULL UNIQUE
                            DEFAULT ('WH/TR/' || lpad(nextval('transfer_reference_seq')::text, 6, '0')),
  source_warehouse_id       UUID NOT NULL REFERENCES warehouses (id) ON DELETE RESTRICT,
  source_location_id        UUID NOT NULL,
  destination_warehouse_id  UUID NOT NULL REFERENCES warehouses (id) ON DELETE RESTRICT,
  destination_location_id   UUID NOT NULL,
  status                    document_status NOT NULL DEFAULT 'DRAFT',
  transfer_date             TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_by                UUID NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  updated_by                UUID REFERENCES users (id) ON DELETE RESTRICT,
  validated_by              UUID REFERENCES users (id) ON DELETE RESTRICT,
  validated_at              TIMESTAMPTZ,
  created_at                TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at                TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT internal_transfers_source_in_warehouse_fk
    FOREIGN KEY (source_location_id, source_warehouse_id) REFERENCES locations (id, warehouse_id) ON DELETE RESTRICT,
  CONSTRAINT internal_transfers_destination_in_warehouse_fk
    FOREIGN KEY (destination_location_id, destination_warehouse_id) REFERENCES locations (id, warehouse_id) ON DELETE RESTRICT,
  CONSTRAINT internal_transfers_distinct_locations CHECK (source_location_id <> destination_location_id),
  CONSTRAINT internal_transfers_done_is_validated
    CHECK (status <> 'DONE' OR (validated_by IS NOT NULL AND validated_at IS NOT NULL))
);
CREATE INDEX internal_transfers_status_idx ON internal_transfers (status);
CREATE INDEX internal_transfers_source_location_id_idx ON internal_transfers (source_location_id);
CREATE INDEX internal_transfers_destination_location_id_idx ON internal_transfers (destination_location_id);
CREATE INDEX internal_transfers_transfer_date_idx ON internal_transfers (transfer_date);

-- 15. internal_transfer_items
CREATE TABLE internal_transfer_items (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  transfer_id  UUID NOT NULL REFERENCES internal_transfers (id) ON DELETE CASCADE,
  product_id   UUID NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
  quantity     NUMERIC(18,3) NOT NULL CHECK (quantity > 0),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT internal_transfer_items_transfer_product_key UNIQUE (transfer_id, product_id)
);
CREATE INDEX internal_transfer_items_product_id_idx ON internal_transfer_items (product_id);

-- =====================================================================
-- ADJUSTMENT
