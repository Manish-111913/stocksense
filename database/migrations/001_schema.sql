-- 16. inventory_adjustments
CREATE TABLE inventory_adjustments (
  id                      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  reference               VARCHAR(50) NOT NULL UNIQUE
                          DEFAULT ('WH/ADJ/' || lpad(nextval('adjustment_reference_seq')::text, 6, '0')),
  product_id              UUID NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
  warehouse_id            UUID NOT NULL REFERENCES warehouses (id) ON DELETE RESTRICT,
  location_id             UUID NOT NULL,
  recorded_quantity       NUMERIC(18,3) NOT NULL CHECK (recorded_quantity >= 0),
  recorded_stock_version  INTEGER NOT NULL DEFAULT 0, -- stock.version when recorded_quantity was read
  physical_quantity       NUMERIC(18,3) NOT NULL CHECK (physical_quantity >= 0),
  difference              NUMERIC(18,3) NOT NULL,
  reason                  VARCHAR(255) NOT NULL,
  notes                   TEXT,
  status                  document_status NOT NULL DEFAULT 'DRAFT',
  created_by              UUID NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  updated_by              UUID REFERENCES users (id) ON DELETE RESTRICT,
  applied_by              UUID REFERENCES users (id) ON DELETE RESTRICT,
  applied_at              TIMESTAMPTZ,
  created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT inventory_adjustments_location_in_warehouse_fk
    FOREIGN KEY (location_id, warehouse_id) REFERENCES locations (id, warehouse_id) ON DELETE RESTRICT,
  CONSTRAINT inventory_adjustments_difference_matches
    CHECK (difference = physical_quantity - recorded_quantity),
  CONSTRAINT inventory_adjustments_done_is_applied
    CHECK (status <> 'DONE' OR (applied_by IS NOT NULL AND applied_at IS NOT NULL))
);
CREATE INDEX inventory_adjustments_status_idx ON inventory_adjustments (status);
CREATE INDEX inventory_adjustments_product_id_idx ON inventory_adjustments (product_id);
CREATE INDEX inventory_adjustments_location_id_idx ON inventory_adjustments (location_id);
CREATE INDEX inventory_adjustments_created_at_idx ON inventory_adjustments (created_at);

